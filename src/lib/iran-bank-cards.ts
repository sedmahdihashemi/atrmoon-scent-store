export function detectIranianBank(cardNumber: string | null | undefined): string | null {
  const digits = (cardNumber ?? "").replace(/\D/g, "");
  if (digits.length < 6) return null;
  return BIN_TO_BANK[digits.slice(0, 6)] ?? null;
}
